"""Implementation of compute-flow brick install."""

from __future__ import annotations

import fnmatch
import shutil
import subprocess
import sys
from collections.abc import Callable, Iterator
from contextlib import contextmanager
from dataclasses import dataclass
from pathlib import Path
from tempfile import TemporaryDirectory
from typing import Any

from brick_manager.cache import write_cache
from brick_manager.catalog import load_required_cache, select_versioned_entry
from brick_manager.cmake_generation import write_brick_cmake
from brick_manager.errors import BrickManagerError
from brick_manager.git_source import checkout_git_source
from brick_manager.identity import BrickSelector, parse_brick_selector
from brick_manager.metadata import (
    load_info_json,
    load_installed_entry_info_json,
    load_installed_info_json,
)
from brick_manager.model_install import reconcile_installed_models
from brick_manager.paths import StatePaths
from brick_manager.test_script import write_test_script


ConfirmCallback = Callable[[Path], bool]
GENERATED_CMAKE_MARKER = "Generated by the Compute Flow brick manager from info.json."


@dataclass(frozen=True)
class InstallResult:
    identity: str
    install_path: Path
    test_script_path: Path | None
    status: str
    removed_models: list[str]
    incompatible_models: list[str]


@dataclass(frozen=True)
class InstallAllResult:
    cache_path: Path
    total: int
    statuses: dict[str, int]


def install_brick(
    state_paths: StatePaths,
    brick: str,
    *,
    force: bool = False,
    confirm: ConfirmCallback | None = None,
) -> InstallResult:
    cache = load_required_cache(state_paths)
    selector = parse_brick_selector(brick)
    version, entry = select_versioned_entry(
        cache,
        selector,
        require_explicit_latest=False,
    )
    info_json = entry["info_json"]
    metadata = entry["metadata"]

    selected = BrickSelector(
        brick_type=selector.brick_type,
        name=selector.name,
        version=version,
    )
    install_path = state_paths.brick_source(selected)
    installed = bool(metadata.get("installed", False))

    if install_path.exists() and installed and not force:
        installed_info_json = load_installed_entry_info_json(entry, selected)
        metadata["installed_info_json"] = installed_info_json
        _write_generated_cmake(install_path)
        test_script_path = write_test_script(
            install_path, selected, installed_info_json
        )
        reconcile_result = reconcile_installed_models(
            state_paths,
            cache,
            selected,
            entry,
            installed_info_json,
        )
        write_cache(state_paths.cache, cache)
        return InstallResult(
            identity=selected.identity,
            install_path=install_path,
            test_script_path=test_script_path,
            status="already_installed",
            removed_models=reconcile_result.removed,
            incompatible_models=reconcile_result.incompatible,
        )
    with _prepared_source(metadata) as source_path:
        source_info_json = load_info_json(source_path)
        _validate_source_metadata(source_info_json, info_json, selected)

        if install_path.exists() and not installed and not force:
            shutil.rmtree(install_path)
        if install_path.exists() and not force:
            raise BrickManagerError(
                f"Install path already exists; use --force to replace it: {install_path}"
            )
        if install_path.exists() and force:
            model_root = state_paths.models / selected.brick_type / selected.name
            _confirm_replace(install_path, model_root, confirm)
            shutil.rmtree(install_path)
            status = "replaced"
        elif installed and not install_path.exists():
            status = "reinstalled_missing"
        else:
            status = "installed"

        try:
            _copy_local_source(source_path, install_path)
            installed_info_json = load_installed_info_json(install_path, selected)
            _validate_source_metadata(installed_info_json, info_json, selected)
            _write_generated_cmake(install_path)
            test_script_path = write_test_script(
                install_path, selected, installed_info_json
            )
            metadata["installed"] = True
            metadata["installed_source_path"] = str(install_path)
            metadata["installed_info_json"] = installed_info_json
            reconcile_result = reconcile_installed_models(
                state_paths,
                cache,
                selected,
                entry,
                installed_info_json,
            )
            _clear_other_installed_versions(state_paths, cache, selected)
            write_cache(state_paths.cache, cache)
        except Exception:
            if status in ("installed", "reinstalled_missing") and install_path.exists():
                shutil.rmtree(install_path)
            raise
    return InstallResult(
        identity=selected.identity,
        install_path=install_path,
        test_script_path=test_script_path,
        status=status,
        removed_models=reconcile_result.removed,
        incompatible_models=reconcile_result.incompatible,
    )


@contextmanager
def _prepared_source(metadata: dict[str, Any]) -> Iterator[Path]:
    source_type = metadata["source_type"]
    if source_type == "local_directory":
        yield Path(metadata["source_path"])
        return
    if source_type != "git":
        raise BrickManagerError(f"Unsupported brick source type: {source_type}")

    with TemporaryDirectory(prefix="compute-flow-git-install-") as temporary_dir:
        source_path = Path(temporary_dir) / "source"
        checkout_git_source(
            metadata["source"],
            metadata["source_ref"],
            metadata["source_commit"],
            source_path,
        )
        yield source_path


def install_all_bricks(
    state_paths: StatePaths,
    *,
    force: bool = False,
    confirm: ConfirmCallback | None = None,
) -> InstallAllResult:
    cache = load_required_cache(state_paths)
    identities = [
        f"{brick}@{version}"
        for brick, versions in sorted(cache.get("bricks", {}).items())
        for version in sorted(versions)
    ]
    statuses = {
        "installed": 0,
        "already_installed": 0,
        "reinstalled_missing": 0,
        "replaced": 0,
    }

    for identity in identities:
        try:
            result = install_brick(
                state_paths,
                identity,
                force=force,
                confirm=confirm,
            )
        except BrickManagerError as error:
            raise BrickManagerError(f"Failed to install {identity}: {error}") from error
        statuses[result.status] = statuses.get(result.status, 0) + 1

    return InstallAllResult(
        cache_path=state_paths.cache,
        total=len(identities),
        statuses=statuses,
    )


def _confirm_replace(
    path: Path,
    model_path: Path,
    confirm: ConfirmCallback | None,
) -> None:
    if confirm is not None:
        if confirm(path):
            return
        raise BrickManagerError("Install cancelled.")

    if not sys.stdin.isatty():
        raise BrickManagerError(
            "Refusing to replace install path without interactive confirmation."
        )

    print(
        f"Replace existing brick install at {path} and remove incompatible related "
        f"model artifacts under {model_path}? [y/N] ",
        end="",
        file=sys.stderr,
        flush=True,
    )
    answer = sys.stdin.readline().strip().lower()
    if answer not in ("y", "yes"):
        raise BrickManagerError("Install cancelled.")


def _validate_source_metadata(
    source_info_json: dict[str, Any],
    cached_info_json: dict[str, Any],
    selector: BrickSelector,
) -> None:
    if source_info_json != cached_info_json:
        raise BrickManagerError(
            f"Brick source metadata changed after {selector.identity} was cached. "
            "Run `compute-flow update` and retry the installation."
        )


def _clear_other_installed_versions(
    state_paths: StatePaths,
    cache: dict[str, Any],
    selected: BrickSelector,
) -> None:
    versions = cache.get("bricks", {}).get(selected.key, {})
    for version, entry in versions.items():
        if version == selected.version:
            continue

        metadata = entry["metadata"]
        if metadata.get("installed_source_path"):
            installed_path = Path(metadata["installed_source_path"])
            managed_root = state_paths.bricks.resolve()
            if installed_path.exists() and installed_path.resolve().is_relative_to(
                managed_root
            ):
                shutil.rmtree(installed_path)
        metadata["installed"] = False
        metadata["installed_source_path"] = None
        metadata["installed_info_json"] = None


def _copy_local_source(source_path: Path, install_path: Path) -> None:
    if _is_git_worktree(source_path):
        _copy_git_worktree(source_path, install_path)
        return

    shutil.copytree(source_path, install_path, ignore=_simple_ignore(source_path))


def _write_generated_cmake(install_path: Path) -> None:
    cmake_path = install_path / "CMakeLists.txt"
    handwritten_path = install_path / "CMakeLists.handwritten.txt"
    if handwritten_path.exists():
        raise BrickManagerError(
            f"Managed brick root must not contain handwritten CMake: {handwritten_path}"
        )
    if cmake_path.is_file() and not _is_generated_cmake(cmake_path):
        raise BrickManagerError(
            f"Managed brick root must not contain handwritten CMake: {cmake_path}"
        )
    write_brick_cmake(install_path, install_path)


def _is_generated_cmake(cmake_path: Path) -> bool:
    try:
        return GENERATED_CMAKE_MARKER in cmake_path.read_text(
            encoding="utf-8",
            errors="ignore",
        )
    except FileNotFoundError:
        return False


def _is_git_worktree(source_path: Path) -> bool:
    result = subprocess.run(
        ["git", "-C", str(source_path), "rev-parse", "--is-inside-work-tree"],
        check=False,
        capture_output=True,
        text=True,
    )
    return result.returncode == 0 and result.stdout.strip() == "true"


def _copy_git_worktree(source_path: Path, install_path: Path) -> None:
    result = subprocess.run(
        [
            "git",
            "-C",
            str(source_path),
            "ls-files",
            "-z",
            "--cached",
            "--others",
            "--exclude-standard",
        ],
        check=True,
        capture_output=True,
        text=True,
    )
    for relative_name in result.stdout.split("\0"):
        if not relative_name:
            continue
        if relative_name == ".gitignore":
            continue
        source_file = source_path / relative_name
        if not source_file.exists():
            continue
        if not source_file.resolve().is_relative_to(source_path.resolve()):
            raise BrickManagerError(
                f"Brick source contains a link outside its root: {relative_name}"
            )
        destination_file = install_path / relative_name
        destination_file.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source_file, destination_file)


def _simple_ignore(source_path: Path) -> Callable[[str, list[str]], set[str]]:
    patterns = _load_gitignore_patterns(source_path)

    def ignore(directory: str, names: list[str]) -> set[str]:
        ignored = {".git", ".gitignore"}
        directory_path = Path(directory)
        for name in names:
            path = directory_path / name
            relative_name = path.relative_to(source_path).as_posix()
            if any(
                fnmatch.fnmatch(name, pattern)
                or fnmatch.fnmatch(relative_name, pattern)
                for pattern in patterns
            ):
                ignored.add(name)
        return ignored

    return ignore


def _load_gitignore_patterns(source_path: Path) -> list[str]:
    gitignore = source_path / ".gitignore"
    if not gitignore.exists():
        return []

    patterns = []
    for line in gitignore.read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if stripped and not stripped.startswith("#"):
            patterns.append(stripped.rstrip("/"))
    return patterns
